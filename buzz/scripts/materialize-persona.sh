#!/usr/bin/env bash
# Materialize a handed-over persona into PERSONA.md so OpenCode's instruction
# layer picks it up (opencode.json -> instructions). No-op when no persona env
# is present, so a missing handoff leaves the file as a placeholder.
set -euo pipefail
target="${1:-/home/admin/buzz/PERSONA.md}"
{
  printf '<!-- Auto-generated by scripts/materialize-persona.sh. Do not hand-edit. -->\n'
  if [[ -n "${BUZZ_ACP_SYSTEM_PROMPT:-}" ]]; then
    printf '\n## Persona\n\n%s\n' "$BUZZ_ACP_SYSTEM_PROMPT"
  fi
  if [[ -n "${BUZZ_ACP_TEAM_INSTRUCTIONS:-}" ]]; then
    printf '\n## Team instructions\n\n%s\n' "$BUZZ_ACP_TEAM_INSTRUCTIONS"
  fi
} > "$target"
# If neither env var was set, restore the placeholder so we don't leave a
# stray empty file that opencode would still try to inject.
if [[ -z "${BUZZ_ACP_SYSTEM_PROMPT:-}" && -z "${BUZZ_ACP_TEAM_INSTRUCTIONS:-}" ]]; then
  cat > "$target" <<'PLACEHOLDER'
<!-- Auto-generated by scripts/materialize-persona.sh from BUZZ_ACP_SYSTEM_PROMPT
     and BUZZ_ACP_TEAM_INSTRUCTIONS. Do not hand-edit; re-run the script. -->
<!-- Empty until a persona is handed over via launch.policy_env. -->
PLACEHOLDER
fi
